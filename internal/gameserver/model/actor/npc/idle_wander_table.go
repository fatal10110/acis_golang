// IdleWanderParams reports the idle-wander timer in seconds and the
// wander-desire weight for npcID. ok is false when that template does
// not queue wander from an empty desire list.
func IdleWanderParams(npcID int) (timer int, weight float64, ok bool) {
	if p, found := idleWanderSpecial[npcID]; found {
		return p[0], float64(p[1]), true
	}
	_, found := slices.BinarySearch(idleWanderIDs, npcID)
	if !found {
		return 0, 0, false
	}
	return 5, 5, true
}

