var byConstantName = func() map[string]Stat {
	m := make(map[string]Stat, numStats)
	for i := Stat(0); i < numStats; i++ {
		m[constantNames[i]] = i
	}
	return m
}()

// ByConstantName resolves name, an exact upper-case constant spelling such
// as a skill's "stat" set value ("MAX_HP"), to its Stat.
func ByConstantName(name string) (Stat, error) {
	if s, ok := byConstantName[name]; ok {
		return s, nil
	}
	return 0, fmt.Errorf("stat: unknown constant name %q", name)
}
