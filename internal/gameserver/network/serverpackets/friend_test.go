package serverpackets

import (
	"bytes"
	"testing"
)

// The friend packets' bytes, written out by hand from the reference
// writeImpl layouts: FriendAddRequestResult (0x77, d), FriendAddRequest
// (0x7d, S), L2Friend (0xfb, d action, d 0, S name, d online, d id),
// L2FriendStatus (0xfc, d online, S name, d id) and L2FriendSay (0xfd, d
// failure message, S receiver, S sender, S message).
func TestFriendPacketBytes(t *testing.T) {
	for _, tc := range []struct {
		name string
		got  []byte
		want []byte
	}{
		{"FriendAddRequestResult accepted", framePayload(t, FrameFriendAddRequestResult(true)), []byte{
			0x77, 0x01, 0x00, 0x00, 0x00,
		}},
		{"FriendAddRequestResult failed", framePayload(t, FrameFriendAddRequestResult(false)), []byte{
			0x77, 0x00, 0x00, 0x00, 0x00,
		}},
		{"FriendAddRequest", framePayload(t, FrameFriendAddRequest("Bo")), []byte{
			0x7d, 'B', 0x00, 'o', 0x00, 0x00, 0x00,
		}},
		{"L2Friend add online", framePayload(t, FrameL2Friend(L2FriendAdd, "Bo", true, 0x01020304)), []byte{
			0xfb,
			0x01, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			'B', 0x00, 'o', 0x00, 0x00, 0x00,
			0x01, 0x00, 0x00, 0x00,
			0x04, 0x03, 0x02, 0x01,
		}},
		{"L2Friend remove by name only", framePayload(t, FrameL2Friend(L2FriendRemove, "Bo", false, 0)), []byte{
			0xfb,
			0x03, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			'B', 0x00, 'o', 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
		}},
		{"L2FriendStatus", framePayload(t, FrameL2FriendStatus(true, "Bo", 7)), []byte{
			0xfc,
			0x01, 0x00, 0x00, 0x00,
			'B', 0x00, 'o', 0x00, 0x00, 0x00,
			0x07, 0x00, 0x00, 0x00,
		}},
		{"L2FriendSay ignored", framePayload(t, FrameL2FriendSay(620, "A", "B", "hi")), []byte{
			0xfd,
			0x6c, 0x02, 0x00, 0x00, // 620
			'A', 0x00, 0x00, 0x00,
			'B', 0x00, 0x00, 0x00,
			'h', 0x00, 'i', 0x00, 0x00, 0x00,
		}},
		{"FriendList", framePayload(t, FrameFriendList([]FriendListEntry{{ObjectID: 9, Name: "On", Online: true}, {ObjectID: 5, Name: "", Online: false}})), []byte{
			0xfa,
			0x02, 0x00, 0x00, 0x00,
			0x09, 0x00, 0x00, 0x00, 'O', 0x00, 'n', 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00,
			0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		}},
		{"EtcStatusUpdate blocking everything", framePayload(t, FrameEtcStatusUpdate(EtcStatus{Blocked: true})), []byte{
			0xf3,
			0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			0x01, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
		}},
	} {
		if !bytes.Equal(tc.got, tc.want) {
			t.Errorf("%s = %x, want %x", tc.name, tc.got, tc.want)
		}
	}
}
