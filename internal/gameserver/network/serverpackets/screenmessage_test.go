package serverpackets

import (
	"bytes"
	"testing"
)

// ExShowScreenMessage as the reference writes a plain text shown for ten
// seconds: 0xfe, 0x0038, type 1, system message -1, position TOP_CENTER
// (2), not hidden, normal size, two unknown zeros, no effect, the time,
// no fading, then the text.
func TestExShowScreenMessageGolden(t *testing.T) {
	want := []byte{
		0xfe, 0x38, 0x00,
		0x01, 0x00, 0x00, 0x00,
		0xff, 0xff, 0xff, 0xff,
		0x02, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x10, 0x27, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		'H', 0x00, 'i', 0x00, 0x00, 0x00,
	}
	if got := framePayload(t, FrameExShowScreenMessage("Hi", 10000)); !bytes.Equal(got, want) {
		t.Fatalf("ExShowScreenMessage = % x, want % x", got, want)
	}
}
