package scriptfp

import "testing"

// TestClassLiteralBindsTypeVariable builds the testdata/javageneric tree,
// whose script calls generic engine methods with a class literal argument:
// the type variable that literal binds types the call's lambda parameters,
// in any argument position, and its returned value. A type variable no
// literal binds stays unknown.
func TestClassLiteralBindsTypeVariable(t *testing.T) {
	fps, err := Build("testdata/javageneric")
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	const want = `# Static fingerprints of the reference script classes: generated by cmd/scriptfp, do not edit.
# Format: README.md in this directory.
classes 1

class script.ai.Generic extends Quest
  numbers 2 3 4 5 250
  call ?.getZ 1
  call Creature.forEachKnownTypeInRadius 3
  call Creature.getAs 1
  call Creature.getKnownTypeInside 1
  call Creature.getZ 1
  call Player.getClan 1
  call Player.teleportTo 3
  hook onCreated none
`
	if got := string(Render(fps)); got != want {
		t.Errorf("Render mismatch\n got:\n%s\nwant:\n%s", got, want)
	}
}
