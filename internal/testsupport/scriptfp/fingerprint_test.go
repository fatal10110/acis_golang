// TestCommittedGoldensAreConsistent runs without the reference checkout:
// the committed fingerprints parse and render back byte for byte, the
// committed census is the census of those fingerprints with apimap.txt, and
// apimap.txt names only census rows.
func TestCommittedGoldensAreConsistent(t *testing.T) {
	fps, err := Parse(committedReference)
	if err != nil {
		t.Fatalf("Parse reference.golden: %v", err)
	}
	if !bytes.Equal(Render(fps), committedReference) {
		t.Fatal("reference.golden does not render back to itself")
	}
	amap, err := APIMap()
	if err != nil {
		t.Fatalf("APIMap: %v", err)
	}
	if !bytes.Equal(Census(fps, amap), committedCensus) {
		t.Fatal("census.golden is stale: regenerate it with go run ./cmd/scriptfp (see the package comment)")
	}
	rows := map[string]bool{}
	for _, fp := range fps {
		for row := range fp.Calls {
			rows[row] = true
		}
	}
	for row := range amap {
		if !rows[row] {
			t.Errorf("apimap.txt maps %s, which no reference class calls", row)
		}
	}
	for _, fp := range fps {
		for row := range fp.Calls {
			if amap[row] == Exempt && !ExemptCaller(fp.Class) {
				t.Errorf("%s calls %s, which is exempt from the API freeze, but is not a class the exemption covers", fp.Class, row)
			}
		}
	}
}

