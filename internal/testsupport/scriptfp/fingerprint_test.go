// The fixture tree under testdata/java holds a stub engine (Quest, Npc,
// Player, Location) and three script classes covering every rule of the
// extractor.
const fixtureReference = `# Static fingerprints of the reference script classes: generated by cmd/scriptfp, do not edit.
# Format: README.md in this directory.
classes 3

class quest.Q900_Fixture extends Quest
  numbers 0.5 2 3 31 57 100 900 3000 30048
  string "30048-01.htm"
  string "Fixture \"quoted\"\n"
  char ";"
  call ?.missing 1
  call Creature.getPosition 1
  call Location.getX 1
  call Location.new 1
  call Npc.getNpcId 3
  call Npc.getObjectId 1
  call Player.getSummons 1
  call Quest.giveItems 1
  call Quest.playSound 1
  hook onAdvEvent direct same
  hook onAttacked direct same
  hook onCreated direct changed
  hook onDecayed helper same
  hook onTalk none

class script.ai.Base extends Quest
  string "ai"
  call Npc.getNpcId 1
  hook onCreated none

class script.ai.Child extends script.ai.Base
  hook onCreated direct same
`

func TestBuildFixtureTree(t *testing.T) {
	fps, err := Build("testdata/java")
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	got := string(Render(fps))
	if got != fixtureReference {
		t.Errorf("Render mismatch\n got:\n%s\nwant:\n%s", got, fixtureReference)
	}
	parsed, err := Parse([]byte(got))
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if !reflect.DeepEqual(parsed, fps) {
		t.Errorf("Parse(Render(fps)) differs from fps:\n%+v\n%+v", parsed, fps)
	}
}

