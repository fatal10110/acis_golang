// fixtureAPIMap maps every engine call of the fixture quest, plus one Quest
// helper the quest never calls.
var fixtureAPIMap = map[string]string{
	"?.missing":            Inline,
	"Creature.getPosition": "Player.Position",
	"Location.getX":        "Location.X",
	"Location.new":         "script.NewLocation",
	"Npc.getNpcId":         "NPC.ID",
	"Npc.getObjectId":      "NPC.ObjectID",
	"Player.getSummons":    "Player.Summons",
	"Quest.giveItems":      "script.GiveItems",
	"Quest.playSound":      "script.PlaySound",
	"Quest.takeItems":      "script.TakeItems",
}

func fixtureCheck(t *testing.T, amap map[string]string, dir string, exempt ...string) []string {
	t.Helper()
	fps, err := Build("testdata/java")
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	problems, err := check(byClass(fps), amap, dir, []string{"quest.Q900_Fixture"}, exempt)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	return problems
}

func TestCheckFaithfulPortHasNoProblem(t *testing.T) {
	if problems := fixtureCheck(t, fixtureAPIMap, "testdata/go/q900"); len(problems) != 0 {
		t.Errorf("problems for a faithful port:\n%s", strings.Join(problems, "\n"))
	}
}

func TestCheckNamesEveryDifference(t *testing.T) {
	got := fixtureCheck(t, fixtureAPIMap, "testdata/go/q900bad")
	want := []string{
		`quest.Q900_Fixture: call Quest.playSound is in the reference but the Go package never calls script.PlaySound`,
		`quest.Q900_Fixture: call Quest.takeItems is not in the reference but the Go package calls script.TakeItems`,
		`quest.Q900_Fixture: char ";" is in the reference but not in the Go package`,
		`quest.Q900_Fixture: hook onAttacked direct changed is in the Go package but not in the reference`,
		`quest.Q900_Fixture: hook onAttacked direct same is in the reference but not in the Go package`,
		`quest.Q900_Fixture: hook onDecayed helper same is in the reference but not in the Go package`,
		`quest.Q900_Fixture: hook onSeeCreature none is in the Go package but not in the reference`,
		`quest.Q900_Fixture: number 57 is in the reference but not in the Go package`,
		`quest.Q900_Fixture: number 58 is in the Go package but not in the reference`,
		`quest.Q900_Fixture: string "extra" is in the Go package but not in the reference`,
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("problems:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func TestCheckUnmappedCallAndExemptions(t *testing.T) {
	amap := map[string]string{}
	for k, v := range fixtureAPIMap {
		amap[k] = v
	}
	delete(amap, "Npc.getObjectId")
	amap["Quest.giveItems"] = Exempt
	got := fixtureCheck(t, amap, "testdata/go/q900", `char ";"`)
	want := []string{
		`quest.Q900_Fixture: call Npc.getObjectId has no Go name in apimap.txt`,
		`quest.Q900_Fixture: call Quest.giveItems is exempt from the API freeze and has no Go name yet`,
		`quest.Q900_Fixture: exemption "char \";\"" matches no difference`,
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("problems:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}

	got = fixtureCheck(t, fixtureAPIMap, "testdata/go/q900bad",
		`number 57`, `number 58`, `string "extra"`, `char ";"`, `call Quest.playSound`, `call Quest.takeItems`,
		`hook onAttacked direct changed`, `hook onAttacked direct same`, `hook onDecayed helper same`,
		`hook onSeeCreature none`)
	if len(got) != 0 {
		t.Errorf("every difference exempted, still reported:\n%s", strings.Join(got, "\n"))
	}
}

// A row whose overloads are separate Go calls matches a call of any of its
// names, and reports them all when the package calls none.
func TestCheckRowWithSeveralGoNames(t *testing.T) {
	amap := maps.Clone(fixtureAPIMap)
	amap["Quest.playSound"] = "script.PlaySoundAt,script.PlaySound"
	if got := fixtureCheck(t, amap, "testdata/go/q900"); len(got) != 0 {
		t.Errorf("problems with the called name second in the list:\n%s", strings.Join(got, "\n"))
	}
	amap["Quest.playSound"] = "script.PlaySoundAt,script.PlaySoundTo"
	got := fixtureCheck(t, amap, "testdata/go/q900")
	want := []string{`quest.Q900_Fixture: call Quest.playSound is in the reference but the Go package never calls script.PlaySoundAt,script.PlaySoundTo`}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("problems:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

