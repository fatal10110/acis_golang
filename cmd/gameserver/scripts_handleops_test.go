const handleOpsFile = "scripts_handleops.go"

// TestScriptHandleOpsAreCurrent derives, from the script sources, the
// kind-specific handle operations each catalog script's hooks reach, and
// fails when scripts_handleops.go, which the seam gate reads at boot, says
// otherwise. ACIS_CAPTURE_GOLDEN=1 rewrites the file.
func TestScriptHandleOpsAreCurrent(t *testing.T) {
	prog, err := handleops.Load(filepath.Join("..", ".."), "./internal/gameserver/script/...")
	if err != nil {
		t.Fatal(err)
	}
	catalog, err := prog.Catalog("scripts.go")
	if err != nil {
		t.Fatal(err)
	}
	built, err := scriptCatalog(scriptCatalogs(nil, nil))
	if err != nil {
		t.Fatal(err)
	}
	if got, want := slices.Sorted(maps.Keys(catalog)), slices.Sorted(maps.Keys(built)); !slices.Equal(got, want) {
		t.Fatalf("the scan reads catalog paths %v from scripts.go, the boot builds %v", got, want)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by TestScriptHandleOpsAreCurrent; DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("import \"github.com/fatal10110/acis_golang/internal/gameserver/script\"\n\n")
	b.WriteString("// scriptHandleOps holds, per catalog script, the kind-specific NPC handle\n")
	b.WriteString("// operations each of its hooks reaches. The script seam gate refuses a\n")
	b.WriteString("// script whose hook reaches one that an NPC the hook runs for lacks.\n")
	b.WriteString("var scriptHandleOps = map[string]script.HandleOps{\n")
	for _, path := range slices.Sorted(maps.Keys(catalog)) {
		ops, err := prog.Script(catalog[path])
		if err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		if len(ops) == 0 {
			continue
		}
		fmt.Fprintf(&b, "%s: {\n", strconv.Quote(path))
		for _, field := range slices.Sorted(maps.Keys(ops)) {
			fmt.Fprintf(&b, "%s: {", strconv.Quote(field))
			for i, op := range ops[field] {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(strconv.Quote(op))
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	want, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}

	if os.Getenv("ACIS_CAPTURE_GOLDEN") != "" {
		if err := os.WriteFile(handleOpsFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(handleOpsFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; rerun this test with ACIS_CAPTURE_GOLDEN=1. Derived:\n%s", handleOpsFile, want)
	}
}

// TestManifestComparisonReportsHandleRefusal: a catalog script whose hook
// reaches a hostile-only handle operation is refused, and reported, when
// the NPCs it is bound to are civilian ones.
func TestManifestComparisonReportsHandleRefusal(t *testing.T) {
	const path = "quest.Q230_TestOfTheSummoner"
	list := []script.Listing{{Path: path}}
	catalog := script.Catalog{path: questCatalog(nil)[path]}
	folk := func(int32) (script.NPCKind, bool) { return script.KindFolk, true }
	got := manifestMismatches(t, list, catalog, script.Config{KindOf: folk, Log: zerolog.Nop(), HandleOps: scriptHandleOps})
	if !slices.Equal(got, []string{"script " + path + " refused"}) {
		t.Fatalf("a script calling a hostile-only operation on civilian npcs gave %q", got)
	}
}
