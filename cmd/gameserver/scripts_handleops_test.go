const handleOpsFile = "scripts_handleops.go"

// catalogDir is the content catalog package.
var catalogDir = filepath.Join("..", "..", "internal", "gameserver", "script", "catalog")

// handleOpsTarget is a Go file holding script catalogs and the generated
// file beside it that holds the handle operations of their scripts: name
// is the variable (package main) or the function (a catalog file) that
// returns them.
type handleOpsTarget struct {
	source, out, pkg, name string
}

// handleOpsTargets returns scripts.go and every catalog file of the content
// catalog package that holds script catalogs.
func handleOpsTargets(t *testing.T) []handleOpsTarget {
	t.Helper()
	out := []handleOpsTarget{{source: "scripts.go", out: handleOpsFile, pkg: "main", name: "scriptHandleOps"}}
	files, err := filepath.Glob(filepath.Join(catalogDir, "*.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range files {
		base := filepath.Base(file)
		if base == "catalog.go" || strings.HasSuffix(base, "_test.go") || strings.HasSuffix(base, "_handleops.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.SkipObjectResolution)
		if err != nil {
			t.Fatal(err)
		}
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok || fn.Type.Results == nil || len(fn.Type.Results.List) != 1 {
				continue
			}
			if sel, ok := fn.Type.Results.List[0].Type.(*ast.SelectorExpr); ok && sel.Sel.Name == "Catalog" {
				out = append(out, handleOpsTarget{source: file, out: strings.TrimSuffix(file, ".go") + "_handleops.go", pkg: "catalog", name: fn.Name.Name + "HandleOps"})
			}
		}
	}
	return out
}

// TestScriptHandleOpsAreCurrent derives, from the script sources, the
// kind-specific handle operations each catalog script's hooks reach, and
// fails when the generated files the seam gate reads at boot say
// otherwise: scripts_handleops.go for the scripts of scripts.go, and one
// file beside each content catalog file for its scripts.
// ACIS_CAPTURE_GOLDEN=1 rewrites the files.
func TestScriptHandleOpsAreCurrent(t *testing.T) {
	prog, err := handleops.Load(filepath.Join("..", ".."), "./internal/gameserver/script/...")
	if err != nil {
		t.Fatal(err)
	}
	built, err := scriptCatalog(scriptCatalogs(nil, nil))
	if err != nil {
		t.Fatal(err)
	}
	scanned := map[string]bool{}
	for _, target := range handleOpsTargets(t) {
		catalog, err := prog.Catalog(target.source)
		if err != nil {
			t.Fatal(err)
		}
		for path := range catalog {
			scanned[path] = true
		}
		want := generateHandleOps(t, prog, catalog, target)
		if os.Getenv("ACIS_CAPTURE_GOLDEN") != "" {
			if err := os.WriteFile(target.out, want, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(target.out)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s is stale; rerun this test with ACIS_CAPTURE_GOLDEN=1. Derived:\n%s", target.out, want)
		}
	}
	if got, want := slices.Sorted(maps.Keys(scanned)), slices.Sorted(maps.Keys(built)); !slices.Equal(got, want) {
		t.Fatalf("the scan reads catalog paths %v, the boot builds %v", got, want)
	}
}

// generateHandleOps returns the generated file of target: the handle
// operations of every script of catalog whose hooks reach one.
func generateHandleOps(t *testing.T, prog *handleops.Program, catalog map[string][]*types.Func, target handleOpsTarget) []byte {
	t.Helper()
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by TestScriptHandleOpsAreCurrent; DO NOT EDIT.\n\npackage %s\n\n", target.pkg)
	b.WriteString("import \"github.com/fatal10110/acis_golang/internal/gameserver/script\"\n\n")
	if target.pkg == "main" {
		b.WriteString("// scriptHandleOps holds, per catalog script, the kind-specific NPC handle\n")
		b.WriteString("// operations each of its hooks reaches. The script seam gate refuses a\n")
		b.WriteString("// script whose hook reaches one that an NPC the hook runs for lacks.\n")
		b.WriteString("var scriptHandleOps = map[string]script.HandleOps{\n")
	} else {
		fmt.Fprintf(&b, "// %s holds, per script of %s, the kind-specific NPC\n", target.name, filepath.Base(target.source))
		b.WriteString("// handle operations each of its hooks reaches.\n")
		fmt.Fprintf(&b, "func %s() map[string]script.HandleOps {\nreturn map[string]script.HandleOps{\n", target.name)
	}
	for _, path := range slices.Sorted(maps.Keys(catalog)) {
		ops, err := prog.Script(catalog[path])
		if err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		if len(ops) == 0 {
			continue
		}
		fmt.Fprintf(&b, "%s: {\n", strconv.Quote(path))
		for _, field := range slices.Sorted(maps.Keys(ops)) {
			fmt.Fprintf(&b, "%s: {", strconv.Quote(field))
			for i, op := range ops[field] {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(strconv.Quote(op))
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	if target.pkg != "main" {
		b.WriteString("}\n")
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// TestManifestComparisonReportsHandleRefusal: a catalog script whose hook
// reaches a hostile-only handle operation is refused, and reported, when
// the NPCs it is bound to are civilian ones.
func TestManifestComparisonReportsHandleRefusal(t *testing.T) {
	const path = "script.feature.NewbieHelper"
	list := []script.Listing{{Path: path}}
	catalog := script.Catalog{path: featureCatalog(nil)[path]}
	folk := func(int32) (script.NPCKind, bool) { return script.KindFolk, true }
	got := manifestMismatches(t, list, catalog, script.Config{KindOf: folk, Log: zerolog.Nop(), HandleOps: scriptHandleOps})
	if !slices.Equal(got, []string{"script " + path + " refused"}) {
		t.Fatalf("a script calling a hostile-only operation on civilian npcs gave %q", got)
	}
}
